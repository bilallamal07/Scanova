"""Markdown report formatter — produces a shareable audit document."""

from __future__ import annotations

import sys
from collections import Counter
from datetime import datetime, timezone
from itertools import groupby
from operator import attrgetter
from typing import TextIO

from skill_scanner import __version__
from skill_scanner.models import Dimension, ScanReport, Severity

_SEV_LABEL = {
    Severity.INFO: "INFO",
    Severity.LOW: "LOW",
    Severity.MEDIUM: "MEDIUM",
    Severity.HIGH: "HIGH",
    Severity.CRITICAL: "CRITICAL",
}

_VERDICT_BADGE = {
    "CLEAN": "![CLEAN](https://img.shields.io/badge/verdict-CLEAN-brightgreen)",
    "LOW_RISK": "![LOW RISK](https://img.shields.io/badge/verdict-LOW__RISK-blue)",
    "WARNING": "![WARNING](https://img.shields.io/badge/verdict-WARNING-yellow)",
    "CRITICAL": "![CRITICAL](https://img.shields.io/badge/verdict-CRITICAL-red)",
}


def format_report(
    report: ScanReport,
    min_severity: Severity = Severity.LOW,
    out: TextIO | None = None,
) -> None:
    """Write a markdown audit report to *out* (defaults to stdout)."""
    if out is None:
        out = sys.stdout

    filtered = [f for f in report.findings if f.severity >= min_severity]
    now = datetime.now(tz=timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    badge = _VERDICT_BADGE.get(report.verdict.value, report.verdict.value)

    lines: list[str] = []
    w = lines.append

    # --- Header ---
    w("# Skill Security Scan Report")
    w("")
    w(f"{badge}")
    w("")
    w("| Field | Value |")
    w("|---|---|")
    w(f"| **Scanned path** | `{report.metadata.scanned_path}` |")
    w(f"| **Files scanned** | {report.metadata.files_scanned} |")
    w(f"| **Duration** | {report.metadata.duration_ms:.0f} ms |")
    w(f"| **Score** | {report.score} / 100 |")
    w(f"| **Verdict** | **{report.verdict.value}** |")
    w(f"| **Generated** | {now} |")
    w(f"| **Scanner** | skill-scanner v{__version__} |")
    w("")
    w("---")
    w("")

    # --- Summary by dimension ---
    w("## Summary")
    w("")

    severities = [Severity.CRITICAL, Severity.HIGH, Severity.MEDIUM, Severity.LOW, Severity.INFO]
    header = "| Dimension | " + " | ".join(_SEV_LABEL[s] for s in severities) + " | Total |"
    separator = "|---|" + "|".join("---" for _ in severities) + "|---|"
    w(header)
    w(separator)

    dimension_findings = {d: [] for d in Dimension}
    for f in filtered:
        dimension_findings[f.dimension].append(f)

    total_by_sev: Counter[Severity] = Counter()
    for dim, flist in dimension_findings.items():
        if not flist:
            continue
        by_sev: Counter[Severity] = Counter(f.severity for f in flist)
        total_by_sev.update(by_sev)
        counts = " | ".join(str(by_sev.get(s, 0)) for s in severities)
        dim_label = dim.value.replace("_", " ").title()
        w(f"| {dim_label} | {counts} | {len(flist)} |")

    grand_total = sum(total_by_sev.values())
    totals = " | ".join(str(total_by_sev.get(s, 0)) for s in severities)
    w(f"| **Total** | {totals} | **{grand_total}** |")
    w("")
    w("---")
    w("")

    # --- Findings by dimension ---
    if not filtered:
        w("## Findings")
        w("")
        w("No findings above the severity threshold.")
    else:
        w("## Findings")
        w("")
        sorted_findings = sorted(filtered, key=lambda f: (f.dimension, -f.severity))
        base = report.metadata.scanned_path

        for dimension, group in groupby(sorted_findings, key=attrgetter("dimension")):
            dim_label = dimension.value.replace("_", " ").title()
            w(f"### {dim_label}")
            w("")
            w("| Severity | Rule | File | Line | Matched text |")
            w("|---|---|---|---|---|")
            for finding in group:
                sev = _SEV_LABEL[finding.severity]
                rel_path = finding.file_path
                if rel_path.startswith(base):
                    rel_path = rel_path[len(base):].lstrip("/") or rel_path
                match = finding.matched_text.replace("|", "\\|")
                if len(match) > 60:
                    match = match[:57] + "..."
                w(f"| {sev} | `{finding.rule_name}` | `{rel_path}` | {finding.line_number} | `{match}` |")
            w("")

    w("---")
    w("")
    w(f"*Generated by [skill-scanner](https://github.com/your-org/skill-scanner) v{__version__}.*")
    w("")

    out.write("\n".join(lines))
